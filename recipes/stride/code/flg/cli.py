"""Command-line reproduction workflow."""
from __future__ import annotations

import argparse
import json
import os
import platform
import time
from dataclasses import asdict
from importlib.metadata import PackageNotFoundError, version
from pathlib import Path

from .io import canonical, digest, file_digest, read_jsonl, write_json, write_jsonl
from .pipeline import RunConfig, Stride


def source_fingerprint() -> str:
    root = Path(__file__).parent
    return digest({str(p.relative_to(root)): file_digest(p) for p in sorted(root.rglob("*"))
                   if p.is_file() and p.suffix in {".py", ".txt"}})


def runtime_versions() -> dict:
    result = {}
    for name in ["torch", "transformers", "vllm", "faiss-gpu-cu12", "faiss-cpu", "numpy"]:
        try:
            result[name] = version(name)
        except PackageNotFoundError:
            pass
    return result


def local_revision(model: str):
    receipt = Path(model) / "source_revision.json"
    return json.loads(receipt.read_text()) if receipt.is_file() else None


def make_backend(args):
    from .backends import CachedBackend, VLLMBackend
    backend = VLLMBackend(args.model, revision=args.revision, tensor_parallel=args.tensor_parallel,
        memory_fraction=args.memory_fraction, max_model_len=args.max_model_len,
        dtype=args.dtype, enforce_eager=args.enforce_eager)
    return CachedBackend(backend, args.cache)


def execute(args) -> None:
    from .retrieval import Contriever, DenseRetriever, CandidatePoolRetriever
    questions = read_jsonl(args.questions)
    if any(set(q) != {"id", "question"} for q in questions):
        raise ValueError("Pass a question-only file generated by flg prepare")
    if args.limit:
        questions = questions[:args.limit]
    questions = questions[args.shard_index::args.num_shards]
    if not questions:
        raise ValueError("No assigned questions")
    out = Path(args.output)
    out.mkdir(parents=True, exist_ok=True)
    if args.cache is None:
        args.cache = str(out / "calls.sqlite")
    runtime = {"source_sha256": source_fingerprint(), "questions_sha256": file_digest(args.questions),
               "assigned_ids": [q["id"] for q in questions], "model": args.model,
               "backend": args.backend, "revision": args.revision, "seed": args.seed,
               "top_k": args.top_k, "max_iterations": 5, "temperature": 1.0,
               "max_tokens": 512, "enable_thinking": False,
               "methods": args.methods.split(","), "index_manifest": json.loads((Path(args.index)/"manifest.json").read_text()),
               "retrieval_scope": "question_candidates" if args.candidate_pools else "global",
               "candidate_pools_sha256": file_digest(args.candidate_pools) if args.candidate_pools else None,
               "python": platform.python_version(), "packages": runtime_versions(),
               "model_source": local_revision(args.model), "encoder_source": local_revision(args.encoder),
               "runtime": {"dtype": args.dtype, "tensor_parallel": args.tensor_parallel,
                           "memory_fraction": args.memory_fraction, "max_model_len": args.max_model_len,
                           "enforce_eager": args.enforce_eager, "batch_size": args.batch_size,
                           "retriever_device": args.retriever_device, "faiss_device": args.faiss_device,
                           "encoder": args.encoder, "encoder_batch_size": args.encoder_batch_size,
                           "concurrency": args.concurrency, "trace_prompts": not args.no_trace_prompts}}
    manifest_path = out / "manifest.json"
    if manifest_path.exists() and json.loads(manifest_path.read_text()) != runtime:
        raise ValueError("Existing run manifest differs. Use a new output directory; do not mix protocols")
    write_json(manifest_path, runtime)
    backend = make_backend(args)
    encoder = Contriever(args.encoder, device=args.retriever_device, batch_size=args.encoder_batch_size)
    retriever = (CandidatePoolRetriever(args.index, encoder, args.candidate_pools,
                                       faiss_device=args.faiss_device) if args.candidate_pools else
                 DenseRetriever(args.index, encoder, faiss_device=args.faiss_device))
    config = RunConfig(top_k=args.top_k, seed=args.seed, trace_prompts=not args.no_trace_prompts)
    runner = Stride(backend, retriever, config)
    plan_path = Path(args.plans) if args.plans else out / "plans.jsonl"
    plans = read_jsonl(plan_path) if plan_path.exists() else []
    known = {str(p["id"]) for p in plans}
    needs_plans = any(m.startswith("stride") for m in args.methods.split(","))
    need = [q for q in questions if str(q["id"]) not in known] if needs_plans else []
    for offset in range(0, len(need), args.batch_size):
        plans.extend(runner.plan(need[offset:offset + args.batch_size]))
        write_jsonl(plan_path, plans)
        print(canonical({"event": "plans", "done": len(plans), "assigned": len(questions)}), flush=True)
    for method in args.methods.split(","):
        stage = {"stride": "none", "stride_fg": "extraction+reasoning",
                 "stride_retrieval": "retrieval", "stride_extraction": "extraction",
                 "stride_reasoning": "reasoning", "stride_all": "all"}.get(method)
        if stage is None:
            raise ValueError("Unknown STRIDE configuration: " + method)
        worker = Stride(backend, retriever, RunConfig(**{**asdict(config), "method": method, "guidance": stage}))
        path = out / f"{method}.jsonl"
        complete = read_jsonl(path) if path.exists() else []
        complete_ids = {str(x["id"]) for x in complete}
        if len(complete_ids) != len(complete) or complete_ids - {str(q["id"]) for q in questions}:
            raise ValueError("Duplicate or unassigned result IDs")
        pending = [q for q in questions if str(q["id"]) not in complete_ids]
        for offset in range(0, len(pending), args.batch_size):
            start = time.monotonic()
            batch = pending[offset:offset + args.batch_size]
            result = worker.run(batch, plans)
            with path.open("a", encoding="utf-8") as f:
                for row in result:
                    f.write(canonical(row) + "\n")
                f.flush()
                os.fsync(f.fileno())
            print(canonical({"event": "batch", "method": method, "completed": len(complete) + offset + len(result),
                "assigned": len(questions), "seconds": time.monotonic() - start,
                "ok": sum(r["status"] == "ok" for r in result)}), flush=True)
    write_json(out / "complete.json", {"complete": True, "n": len(questions), "methods": args.methods.split(","),
                                       "manifest_sha256": file_digest(manifest_path)})


def build_parser():
    p = argparse.ArgumentParser(prog="flg", description="Forward-Looking Guidance reproducibility tools")
    sub = p.add_subparsers(dest="command", required=True)
    d = sub.add_parser("prepare", help="Prepare fixed splits and a global corpus from the IRCoT archive")
    d.add_argument("--archive", required=True)
    d.add_argument("--output", required=True)
    d.add_argument("--seed", type=int, default=42)
    d.add_argument("--exclude-train-n", type=int, default=10000)
    d.add_argument("--extra-n", type=int, default=500)
    idx = sub.add_parser("index", help="Build a Contriever/FAISS index")
    idx.add_argument("--corpus", required=True)
    idx.add_argument("--output", required=True)
    idx.add_argument("--encoder", default="facebook/contriever")
    idx.add_argument("--revision")
    idx.add_argument("--passage-input", choices=["body", "title_body"], default="title_body")
    idx.add_argument("--device", default="cuda")
    idx.add_argument("--faiss-device", choices=["cuda", "cpu"], default="cuda")
    idx.add_argument("--batch-size", type=int, default=64)
    r = sub.add_parser("run", help="Generate shared plans and execute paired methods")
    r.add_argument("--questions", required=True)
    r.add_argument("--index", required=True)
    r.add_argument("--candidate-pools", help="Use complete public question candidate pools instead of global retrieval")
    r.add_argument("--encoder", default="facebook/contriever")
    r.add_argument("--output", required=True)
    r.add_argument("--backend", choices=["vllm"], required=True)
    r.add_argument("--model", required=True)
    r.add_argument("--revision")
    r.add_argument("--methods", default="stride,stride_fg")
    r.add_argument("--top-k", type=int, choices=[3, 5], required=True)
    r.add_argument("--seed", type=int, default=42)
    r.add_argument("--batch-size", type=int, default=32)
    r.add_argument("--limit", type=int, default=0)
    r.add_argument("--num-shards", type=int, default=1)
    r.add_argument("--shard-index", type=int, default=0)
    r.add_argument("--plans")
    r.add_argument("--cache")
    r.add_argument("--concurrency", type=int, default=16)
    r.add_argument("--tensor-parallel", type=int, default=1)
    r.add_argument("--memory-fraction", type=float, default=.82)
    r.add_argument("--max-model-len", type=int, default=8192)
    r.add_argument("--dtype", choices=["auto", "float16", "bfloat16", "float32"], default="auto")
    r.add_argument("--enforce-eager", action="store_true")
    r.add_argument("--retriever-device", choices=["cuda", "cpu"], default="cuda")
    r.add_argument("--faiss-device", choices=["cuda", "cpu"], default="cuda")
    r.add_argument("--encoder-batch-size", type=int, default=64)
    r.add_argument("--no-trace-prompts", action="store_true")
    e = sub.add_parser("evaluate", help="Score saved predictions with separate gold labels")
    e.add_argument("--predictions", required=True, nargs="+")
    e.add_argument("--labels", required=True)
    e.add_argument("--output", required=True)
    e.add_argument("--allow-partial", action="store_true")
    return p


def main(argv=None):
    args = build_parser().parse_args(argv)
    if args.command == "prepare":
        from .data import prepare
        report = prepare(args.archive, args.output, seed=args.seed,
                         exclude_train_n=args.exclude_train_n, extra_n=args.extra_n)
        print(canonical({k: {a: v[a] for a in ["test_n", "dev_n", "corpus_n"]}
                         for k, v in report["datasets"].items()}))
    elif args.command == "index":
        from .retrieval import Contriever, build_index
        encoder = Contriever(args.encoder, device=args.device, revision=args.revision,
                             batch_size=args.batch_size, passage_input=args.passage_input)
        print(canonical(build_index(args.corpus, args.output, encoder, faiss_device=args.faiss_device)))
    elif args.command == "run":
        if args.num_shards < 1 or not 0 <= args.shard_index < args.num_shards:
            raise ValueError("Invalid shard assignment")
        execute(args)
    elif args.command == "evaluate":
        from .metrics import evaluate
        rows = [row for path in args.predictions for row in read_jsonl(path)]
        result = evaluate(rows, read_jsonl(args.labels), allow_partial=args.allow_partial)
        result["prediction_files"] = {path: file_digest(path) for path in args.predictions}
        result["labels_sha256"] = file_digest(args.labels)
        write_json(args.output, result)
        print(json.dumps(result, indent=2))


if __name__ == "__main__":
    main()
